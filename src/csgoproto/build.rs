use std::{
    fs,
    io::Result,
    path::{Path, PathBuf},
    process::{Command, ExitStatus},
    time::{Duration, SystemTime, UNIX_EPOCH},
};

#[path = "build_support/delta_patch.rs"]
mod delta_patch;

const REPO_URL: &str = "https://github.com/SteamDatabase/GameTracking-CS2.git";
const PROTOBUF_FILE: &str = "generated_protobuf.rs";
const STALE_CLONE_AGE: Duration = Duration::from_secs(60 * 60);
const GENERATED_HEADER: &str = "// AUTO-GENERATED — DO NOT EDIT. Regenerated by src/csgoproto/build.rs (cargo build -p counterstrat-demoparser); tag 6 delta_data is re-applied after prost-build. This file is gitignored.\n";

const PROTO_NAMES: &[&str] = &[
    "steammessages.proto",
    "gcsdk_gcmessages.proto",
    "demo.proto",
    "cstrike15_gcmessages.proto",
    "cstrike15_usermessages.proto",
    "usermessages.proto",
    "networkbasetypes.proto",
    "engine_gcmessages.proto",
    "netmessages.proto",
    "network_connection.proto",
    "cs_usercmd.proto",
    "usercmd.proto",
    "gameevents.proto",
    "cs_gameevents.proto",
];

fn main() -> Result<()> {
    let mirror = git_mirror::mirror_path().map_err(std::io::Error::other)?;
    let protos: Vec<PathBuf> = PROTO_NAMES.iter().map(|name| mirror.join("Protobufs").join(name)).collect();

    for proto in &protos {
        println!("cargo::rerun-if-changed={}", proto.display());
    }

    fetch_protos(&mirror, &protos)?;
    generate_protobuf(&mirror, &protos)
}

fn generate_protobuf(mirror: &Path, protos: &[PathBuf]) -> Result<()> {
    let out_dir = std::env::var("OUT_DIR").map_err(std::io::Error::other)?;
    let generated_dir = Path::new(&out_dir).join("protobuf");
    fs::create_dir_all(&generated_dir)?;

    let include_dir = mirror.join("Protobufs");
    prost_build::Config::new()
        .format(false)
        .out_dir(&generated_dir)
        .default_package_filename("protobuf")
        .bytes(["."])
        .enum_attribute(".", "#[derive(::strum::EnumIter)]")
        .compile_protos(protos, std::slice::from_ref(&include_dir))?;

    let generated = fs::read_to_string(generated_dir.join("protobuf.rs"))?;
    let generated = delta_patch::patch(&with_header(generated));
    let source_dir = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("src");
    write_if_changed(&source_dir.join(PROTOBUF_FILE), generated.as_bytes())
}

fn with_header(generated: String) -> String {
    if generated.starts_with(GENERATED_HEADER) {
        return generated;
    }
    format!("{GENERATED_HEADER}{generated}")
}

fn write_if_changed(path: &Path, contents: &[u8]) -> Result<()> {
    if fs::read(path).is_ok_and(|existing| existing == contents) {
        return Ok(());
    }
    fs::write(path, contents)
}

// Only this build script writes GameTracking-CS2, but concurrent cargo
// invocations in the same checkout can still race. Rather than serialise them
// behind a lock (a fixed wait can hang on a lock left by a killed build), each
// racer is allowed to fetch its own copy: concurrent fresh builds may both
// clone (~3s in parallel, one discarded). Publication re-checks the protos and
// leaves a complete checkout untouched, so the first complete result wins and
// no waiting or stale-lock hang is possible.
fn fetch_protos(mirror: &Path, protos: &[PathBuf]) -> Result<()> {
    let mut sync_error = None;

    if mirror.is_dir() {
        if mirror.join(".git").exists() {
            if let Err(err) = git_mirror::sync(mirror) {
                sync_error = Some(err);
            }

            if protos_present(protos) {
                if let Some(reason) = &sync_error {
                    // An offline or unreachable upstream must not fail the build;
                    // the existing checkout is still usable.
                    println!("cargo::warning=csgoproto build: upstream sync failed ({reason}); using existing local protos");
                }
                return Ok(());
            }
        } else {
            // A checkout without git metadata cannot be refreshed and may be a
            // truncated manual copy, so replace it instead of trusting it.
            println!("cargo::warning=csgoproto build: {} is not a git checkout; re-cloning", mirror.display());
        }
    }

    // The fetch runs at build time on CI hosts, where a transient network
    // failure would otherwise fail the whole wheel build.
    let mut clone_attempts = Vec::new();
    for _ in 0..2 {
        clone_attempts.push(match clone_repo(mirror, protos) {
            Ok(status) => status.to_string(),
            Err(err) => format!("error: {err}"),
        });
        if protos_present(protos) {
            return Ok(());
        }
    }

    let missing: Vec<String> = protos
        .iter()
        .filter(|proto| !proto.is_file())
        .map(|proto| proto.display().to_string())
        .collect();
    Err(std::io::Error::other(format!(
        "csgoproto build: proto sync failed (sync: {sync_error:?}, clone: {clone_attempts:?}); missing: {missing:?}"
    )))
}

fn clone_repo(mirror: &Path, protos: &[PathBuf]) -> Result<ExitStatus> {
    sweep_stale_clones(mirror);
    let staging = staging_dir(mirror);

    let status = Command::new("git").args(["clone", REPO_URL, "--depth=1"]).arg(&staging).status()?;
    if !status.success() {
        let _ = fs::remove_dir_all(&staging);
        return Ok(status);
    }

    if let Err(err) = replace_dir(&staging, mirror, protos) {
        let _ = fs::remove_dir_all(&staging);
        return Err(err);
    }
    Ok(status)
}

// Pid-only staging names can collide across containers or reused pids. The pid
// plus timestamp keeps concurrent builds separate. The age-based sweep only
// removes leftovers from killed builds, never a clone another build is still
// writing.
fn staging_dir(mirror: &Path) -> PathBuf {
    let name = mirror.file_name().and_then(|name| name.to_str()).unwrap_or("GameTracking-CS2");
    let nanos = SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .map(|elapsed| elapsed.as_nanos())
        .unwrap_or_default();
    let parent = mirror.parent().unwrap_or_else(|| Path::new("."));

    parent.join(format!("{name}.clone.{}.{nanos}", std::process::id()))
}

fn sweep_stale_clones(mirror: &Path) {
    let Some(parent) = mirror.parent() else {
        return;
    };
    let Some(name) = mirror.file_name().and_then(|name| name.to_str()) else {
        return;
    };
    let prefix = format!("{name}.clone.");
    let Ok(entries) = fs::read_dir(parent) else {
        return;
    };

    for entry in entries.flatten() {
        if !entry.file_name().to_string_lossy().starts_with(&prefix) {
            continue;
        }
        let stale = entry
            .metadata()
            .and_then(|metadata| metadata.modified())
            .ok()
            .and_then(|modified| modified.elapsed().ok())
            .is_some_and(|age| age > STALE_CLONE_AGE);
        if stale {
            let _ = fs::remove_dir_all(entry.path());
        }
    }
}

fn replace_dir(staging: &Path, target: &Path, protos: &[PathBuf]) -> Result<()> {
    // Another build may have published a complete checkout while this one was
    // cloning; keep that one and discard our staging copy.
    if target.join(".git").exists() && protos_present(protos) {
        let _ = fs::remove_dir_all(staging);
        return Ok(());
    }

    if let Err(err) = fs::remove_dir_all(target) {
        if err.kind() != std::io::ErrorKind::NotFound {
            return Err(err);
        }
    }

    match fs::rename(staging, target) {
        Ok(()) => Ok(()),
        Err(_) if target.join(".git").exists() && protos_present(protos) => {
            let _ = fs::remove_dir_all(staging);
            Ok(())
        }
        Err(err) => Err(err),
    }
}

fn protos_present(protos: &[PathBuf]) -> bool {
    protos.iter().all(|proto| proto.is_file())
}
